"""
Publish simulated time-series data to the CDF-hosted MQTT broker.

Usage
-----
    python mqtt_publisher.py <num_timeseries> <frequency>

Arguments
---------
    num_timeseries  Number of time series to publish (e.g. 10)
    frequency       Publishing rate, suffixed with "hz" or "s"
                    Examples: 1hz  0.5hz  10hz  2s  0.1hz

Connection details are read from the repo-root .env written by mqtt_extractor_setup.ipynb:

    MQTT_HOST      Broker hostname
    MQTT_PORT      Broker port (default 8883)
    MQTT_USERNAME  MQTT username   (generated by CDF on source creation)
    MQTT_PASSWORD  MQTT password   (generated by CDF on source creation)

Payload format (Cognite MQTT native format)
-------------------------------------------
Each publish cycle sends one MQTT message per chunk of CHUNK_SIZE time series:

    {"timeseriesData": [{"externalId": "...", "items": [{"timestamp": ..., "value": ...}]}]}

Time series external IDs: mqtt_demo_ts_000000 … mqtt_demo_ts_NNNNNN  (up to 999 999)
The extractor auto-creates each DM time series node on its first datapoint.

Memory and throughput design notes
-----------------------------------
When testing at high volume (e.g. 100 000 time series at 10 Hz) two naive approaches
both cause runaway memory growth:

1. QoS 1 (at-least-once) with paho-mqtt
   paho keeps every published message in an internal outbound queue until the broker
   sends a PUBACK acknowledgement.  At high publish rates the broker can't keep up,
   so the queue grows without bound — each waiting slot holds the full serialised
   payload.  With 100 000 time series the payload per message is ~10 MB, so even
   a few hundred queued messages exhaust available RAM.
   Fix: use QoS 0 (fire-and-forget).  No ACK → no queue → flat memory.

2. One giant payload per tick
   Serialising 100 000 time series into a single JSON blob takes ~100 ms on modern
   hardware, immediately overrunning a 10 Hz tick budget.  The broker also applies
   back-pressure when it receives a very large message, which compounds QoS 1 issues.
   Fix: chunk into messages of at most CHUNK_SIZE time series (~100 KB each).
   The broker handles 100 small messages per tick far better than one 10 MB blob.

Both fixes are applied here: QoS = 0 and CHUNK_SIZE = 1 000.
"""

import argparse
import json
import math
import os
import ssl
import sys
import time
from pathlib import Path

import paho.mqtt.client as mqtt
from dotenv import load_dotenv

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

MQTT_TOPIC = "cdf/data"
MQTT_PORT = 8883

# Max time series per MQTT message.  Large single payloads cause broker
# back-pressure: the paho outbound queue fills up → unbounded memory growth.
CHUNK_SIZE = 1_000

# Hard cap on paho's outbound queue.  Drops messages rather than accumulating.
MAX_QUEUED = 200

# QoS 0 = fire-and-forget.  QoS 1 would buffer every message until the broker
# ACKs it — at high throughput that causes the same memory blowup as above.
QOS = 0

LOG_INTERVAL_S = 10


# ---------------------------------------------------------------------------
# Argument parsing
# ---------------------------------------------------------------------------


def parse_frequency(value: str) -> float:
    """Return the publish interval in seconds from a frequency string."""
    v = value.lower().strip()
    if v.endswith("hz"):
        hz = float(v[:-2])
        if hz <= 0:
            raise argparse.ArgumentTypeError("Frequency must be > 0")
        return 1.0 / hz
    if v.endswith("s"):
        seconds = float(v[:-1])
        if seconds <= 0:
            raise argparse.ArgumentTypeError("Interval must be > 0")
        return seconds
    raise argparse.ArgumentTypeError(
        f"Cannot parse '{value}'. Use e.g. '1hz', '10hz', '0.5hz', '2s'."
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Publish simulated data to the CDF-hosted MQTT broker.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "num_timeseries", type=int, help="Number of time series (e.g. 10)"
    )
    parser.add_argument(
        "frequency", type=parse_frequency, help="Rate, e.g. '1hz', '0.5hz', '2s'"
    )
    return parser.parse_args()


# ---------------------------------------------------------------------------
# Data simulation
# ---------------------------------------------------------------------------


def make_payload(chunk: list[str], offset: int, num_ts: int, t: float) -> bytes:
    """Return a Cognite-format MQTT payload for one chunk of time series.

    Each time series gets a sine-wave value with a phase offset proportional
    to its global index, so all N series are spread evenly across the cycle.
    """
    ts_now_ms = int(time.time() * 1000)
    items = []
    for local_i, ext_id in enumerate(chunk):
        global_i = offset + local_i
        phase = 2 * math.pi * global_i / max(num_ts, 1)
        value = round(math.sin(2 * math.pi * t / 60 + phase) * 50 + 50, 4)
        items.append(
            {"externalId": ext_id, "items": [{"timestamp": ts_now_ms, "value": value}]}
        )
    return json.dumps({"timeseriesData": items}).encode()


# ---------------------------------------------------------------------------
# MQTT callbacks
# ---------------------------------------------------------------------------

_connected = False


def on_connect(client, userdata, flags, reason_code, properties=None):
    global _connected
    if reason_code == 0:
        _connected = True
        print("Connected to MQTT broker.")
    else:
        print(f"Connection failed — reason code: {reason_code}", file=sys.stderr)
        print(
            "Hint: MQTT credentials are only valid for the source they were generated with.\n"
            "Re-run the setup notebook to create a fresh source and update the repo-root .env file.",
            file=sys.stderr,
        )
        sys.exit(1)


def on_disconnect(client, userdata, disconnect_flags, reason_code, properties=None):
    global _connected
    _connected = False
    if reason_code != 0:
        print(f"Unexpected disconnect (reason code {reason_code})", file=sys.stderr)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> None:
    args = parse_args()

    repo_root = Path(__file__).resolve().parent.parent
    load_dotenv(repo_root / ".env")
    host = os.environ.get("MQTT_HOST", "")
    port = int(os.environ.get("MQTT_PORT", str(MQTT_PORT)))
    username = os.environ.get("MQTT_USERNAME", "")
    password = os.environ.get("MQTT_PASSWORD", "")

    if not all([host, username, password]):
        print(
            "ERROR: MQTT_HOST, MQTT_USERNAME and MQTT_PASSWORD must all be set in the repo-root .env.\n"
            "Run mqtt_extractor_setup.ipynb to create a fresh source.",
            file=sys.stderr,
        )
        sys.exit(1)

    num_ts = args.num_timeseries
    interval_s = args.frequency
    hz = 1.0 / interval_s
    ext_ids = [f"mqtt_demo_ts_{i:06d}" for i in range(num_ts)]
    chunks = [ext_ids[i : i + CHUNK_SIZE] for i in range(0, num_ts, CHUNK_SIZE)]
    n_chunks = len(chunks)

    print(
        f"Publishing {num_ts} time series at {hz:.3g} Hz  (interval {interval_s:.3g} s)"
    )
    print(f"  Broker     : {host}:{port}")
    print(f"  Topic      : {MQTT_TOPIC}")
    print(f"  TS IDs     : {ext_ids[0]} … {ext_ids[-1]}")
    print(
        f"  Chunk size : {CHUNK_SIZE}  →  {n_chunks} message(s) per tick  (QoS {QOS})"
    )
    print("Press Ctrl-C to stop.\n")

    mqttc = mqtt.Client(mqtt.CallbackAPIVersion.VERSION2)
    mqttc.username_pw_set(username, password)
    mqttc.tls_set_context(ssl.create_default_context())
    mqttc.max_queued_messages_set(MAX_QUEUED)
    mqttc.on_connect = on_connect
    mqttc.on_disconnect = on_disconnect

    mqttc.connect(host, port, keepalive=60)
    mqttc.loop_start()

    deadline = time.monotonic() + 10
    while not _connected and time.monotonic() < deadline:
        time.sleep(0.05)
    if not _connected:
        print("ERROR: Could not connect within 10 seconds.", file=sys.stderr)
        sys.exit(1)

    tick = 0
    start = time.monotonic()
    last_log = start - LOG_INTERVAL_S
    try:
        while True:
            t = time.monotonic() - start

            for chunk_i, chunk in enumerate(chunks):
                mqttc.publish(
                    MQTT_TOPIC,
                    make_payload(chunk, chunk_i * CHUNK_SIZE, num_ts, t),
                    qos=QOS,
                )

            tick += 1

            now = time.monotonic()
            if now - last_log >= LOG_INTERVAL_S:
                elapsed = now - start
                total_dp = tick * num_ts
                rate = total_dp / elapsed if elapsed > 0 else 0
                print(
                    f"  t={t:6.0f}s  ticks={tick:,}  messages={tick * n_chunks:,}"
                    f"  dps={total_dp:,}  ({rate:,.0f} dps/s)",
                    flush=True,
                )
                last_log = now

            next_tick = start + tick * interval_s
            sleep_for = next_tick - time.monotonic()
            if sleep_for > 0:
                time.sleep(sleep_for)

    except KeyboardInterrupt:
        elapsed = time.monotonic() - start
        total_dp = tick * num_ts
        print(
            f"\nStopped.  ticks={tick:,}  messages={tick * n_chunks:,}"
            f"  dps={total_dp:,}  avg {total_dp / elapsed if elapsed else 0:,.0f} dps/s"
        )
    finally:
        mqttc.loop_stop()
        mqttc.disconnect()


if __name__ == "__main__":
    main()
